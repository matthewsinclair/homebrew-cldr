class Cldr < Formula
  desc "Re-runnable renderer for a plain-text time journal"
  homepage "https://github.com/matthewsinclair/cldr"
  url "https://github.com/matthewsinclair/cldr/releases/download/v0.2.3/cldr-0.2.3-aarch64-apple-darwin.tar.gz"
  sha256 "8181290083d8dc1d18e537fca6a5541eb7cca3e1656b5568fe789d4e05280ef8"
  license "MIT"

  # macOS on Apple silicon: cldr reads BusyCal's store
  depends_on arch: :arm64
  depends_on :macos

  # The designated requirement cldr is signed to: its identifier, then a
  # Developer ID certificate for Geodica's team
  REQUIREMENT = "identifier \"com.geodica.cldr\" and anchor apple generic " \
                "and certificate 1[field.1.2.840.113635.100.6.2.6] " \
                "and certificate leaf[field.1.2.840.113635.100.6.1.13] " \
                "and certificate leaf[subject.OU] = \"76BQL8L47U\"".freeze

  def verify_signature
    system "/usr/bin/codesign", "--verify", "--strict", "-R=#{REQUIREMENT}", libexec/"bin/cldr"
  end

  def install
    # GENERATED by devbin's formula built-in: the publish, or the release's
    # assets laid out with T3's manifest, then the tool's link set.
    if (buildpath/"bin/devbin").exist?
      system "bin/devbin", "install", "--prefix", libexec, "--managed-by", "brew"
    else
      if buildpath.basename.to_s == "bin"
        (libexec/"bin").install Dir["*"]
      else
        libexec.mkpath
        cp_r Dir["*"], libexec, preserve: true
      end
      chmod 0755, libexec/"bin/cldr"
      files = Dir.glob("**/*", File::FNM_DOTMATCH, base: libexec).select do |f|
        (libexec/f).file? && !(libexec/f).symlink? && f != ".cldr-install"
      end
      lines = [
        "# tool: cldr",
        "# version: 0.2.3",
        "# source_commit: fe1bda57db41cc5dce3b02557713f0a5f1ca3e27",
        "# managed_by: brew",
        "# line: cldr 0.2.3 (brew, fe1bda57db41)",
      ]
      lines += files.sort.map do |f|
        sum = (libexec/f).sha256

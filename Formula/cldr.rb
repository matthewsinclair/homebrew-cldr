      end
      (libexec/".cldr-install").write("#{lines.join("\n")}\n")
    end
    bin.install_symlink libexec/"bin/cldr"
    # The example config, where README.md says it is: share/cldr/config.toml
    pkgshare.install_symlink libexec/"config.toml"
    verify_signature
  end

  # GENERATED by devbin's formula built-in: T3's manifest re-hashed once
  # Homebrew has relocated and re-signed the keg's native files.
  post_install_steps do
    run "/bin/sh",
        args:           [
          "-c",
          "set -eu; " \
          'cd "$1"; ' \
          "m=$2; " \
          "t=$m.rehash; " \
          'trap "rm -f -- $t" EXIT; ' \
          'if command -v shasum >/dev/null 2>&1; then h="shasum -a 256"; else h=sha256sum; fi; ' \
          'awk "b && /^#/ { exit 1 } !/^#/ { b = 1 }" "$m" || ' \
          '{ echo "$m: a # line follows a file line, so it is left as it was" >&2; exit 1; }; ' \
          'bad=$(grep -v "^#" "$m" | grep -v -E "^[0-9a-f]{64}  ." || :); ' \
          '[ -z "$bad" ] || { echo "$m: not a file line: $bad, so it is left as it was" >&2; exit 1; }; ' \
          'n=$(grep -c -v "^#" "$m") || { echo "$m lists no file, so it is left as it was" >&2; exit 1; }; ' \
          'grep "^#" "$m" >"$t" || :; ' \
          'grep -v "^#" "$m" | cut -c67- | tr "\n" "\000" | xargs -0 $h -- >>"$t" || ' \
          '{ echo "$m: a file it lists could not be hashed, so it is left as it was" >&2; exit 1; }; ' \
          '[ "$(grep -c -v "^#" "$t")" = "$n" ] || ' \
          '{ echo "$m: a file it lists has no new row, so it is left as it was" >&2; exit 1; }; ' \
          'mv -f -- "$t" "$m"',
          "sh",
          "{{libexec}}",
          ".cldr-install",
        ],
        writable_paths: ["{{libexec}}"]
  end

  def caveats
    <<~EOS
      If you also run cldr from a checkout, `bin/devbin use brew`, run in that
      checkout, hands the cldr command back to Homebrew.
    EOS
  end

  test do
    verify_signature
    assert_match "cldr #{version} (brew, ", shell_output("#{bin}/cldr --version")
    (testpath/"config.toml").write("[journal]\n")
    assert_match "config", shell_output("#{bin}/cldr --config #{testpath}/config.toml paths")
  end
end
